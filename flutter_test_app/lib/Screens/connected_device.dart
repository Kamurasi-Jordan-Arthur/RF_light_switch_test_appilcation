      int softwareCRC(List<int> data) {
        const int crc32Poly = 0xEDB88320;
        int crc = 0xFFFFFFFF;

        for (final byte in data) {
          crc = (crc ^ byte) & 0xFFFFFFFF; // mask to 32-bit
          for (int j = 0; j < 8; j++) {
            int mask = -(crc & 1) & 0xFFFFFFFF;
            crc = ((crc >> 1) ^ (crc32Poly & mask)) & 0xFFFFFFFF;
          }
        }

        return crc & 0xFFFFFFFF;
      }


